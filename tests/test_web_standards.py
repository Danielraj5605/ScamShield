"""Quality gate for the public web pages. These rules are deliberate product decisions:
no emoji, no em-dashes, no gradients, no animation, no 'made with' badge, no third-party
resources, no inline styles, no marketing buzzwords, and every page carries a favicon and
links to the privacy policy and terms."""
import re
from html.parser import HTMLParser

from conftest import ROOT

WEB = ROOT / "web"
PAGES = ["index.html", "how-it-works.html", "privacy.html", "terms.html"]
TEXT_FILES = PAGES + ["style.css", "app.js"]
ROUTES = {"/", "/how-it-works", "/privacy", "/terms", "/favicon.svg", "/favicon.ico", "/apple-touch-icon.png"}

EMOJI = re.compile("[\U0001F000-\U0001FAFF☀-➿⬀-⯿←-⇿️‍✅❌]")
DASHES = re.compile("[–—]")
BUZZWORDS = ["revolutionary", "cutting-edge", "cutting edge", "seamless", "supercharge", "unlock the power",
             "game-changing", "game changing", "world-class", "next-generation", "next generation", "empower",
             "leverage", "state-of-the-art", "state of the art", "elevate", "effortless"]


def read(name):
    return (WEB / name).read_text(encoding="utf-8")


def test_all_web_files_exist():
    for name in TEXT_FILES + ["favicon.svg", "favicon.ico", "apple-touch-icon.png",
                              "fonts/IBMPlexSans-Light-Latin1.woff2", "fonts/IBMPlexSans-Regular-Latin1.woff2", "fonts/IBMPlexSans-Medium-Latin1.woff2",
                              "fonts/IBMPlexSans-Bold-Latin1.woff2", "fonts/IBMPlexMono-Regular-Latin1.woff2",
                              "fonts/OFL-LICENSE.txt"]:
        assert (WEB / name).is_file(), name


def test_no_emoji_or_dashes_in_site_text():
    for name in TEXT_FILES:
        text = read(name)
        assert not EMOJI.search(text), f"emoji or pictograph in {name}"
        assert not DASHES.search(text), f"en/em dash in {name}"


def test_no_gradients_animation_or_cursor_effects():
    css = read("style.css").lower()
    for banned in ("gradient(", "@keyframes", "animation:", "animation-", "transition:", "cursor: url", "cursor:url"):
        assert banned not in css, banned
    js = read("app.js").lower()
    for banned in ("requestanimationframe", "mousemove", "behavior: \"smooth\"", "behavior:'smooth'"):
        assert banned not in js, banned


def test_no_made_with_tag_or_buzzwords():
    for name in PAGES:
        text = read(name).lower()
        for badge in ("made with ai", "made with love", "made with claude", "built with ai", "built with claude",
                      "powered by ai", "generated by ai", "generated with", "lovable", "bolt.new", "v0.dev", "created with ai"):
            assert badge not in text, f"{badge!r} badge text in {name}"
        for word in BUZZWORDS:
            assert word not in text, f"{word!r} in {name}"


class _Page(HTMLParser):
    def __init__(self):
        super().__init__()
        self.tags, self.ids, self.hrefs, self.resources, self.inline_style = [], set(), [], [], False
        self.h1 = 0
        self.lang = self.viewport = None
        self.rels = []

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        self.tags.append(tag)
        if "id" in a:
            self.ids.add(a["id"])
        if "style" in a:
            self.inline_style = True
        if tag == "html":
            self.lang = a.get("lang")
        if tag == "meta" and a.get("name") == "viewport":
            self.viewport = a.get("content")
        if tag == "h1":
            self.h1 += 1
        if tag == "a" and "href" in a:
            self.hrefs.append(a["href"])
        if tag == "link":
            self.rels.append(a.get("rel"))
            self.resources.append(a.get("href"))
        if tag in ("script", "img") and "src" in a:
            self.resources.append(a["src"])


def parse(name):
    p = _Page()
    p.feed(read(name))
    return p


def test_each_page_has_the_required_structure():
    for name in PAGES:
        p = parse(name)
        html = read(name)
        assert p.lang == "en", name
        assert p.viewport and "width=device-width" in p.viewport, name
        assert re.search(r"<title>[^<]{5,}</title>", html), name
        assert p.h1 == 1, f"{name} must have exactly one h1"
        assert "icon" in p.rels and "apple-touch-icon" in p.rels, f"favicon links missing in {name}"
        assert 'class="skip"' in html, f"skip link missing in {name}"
        assert not p.inline_style, f"inline style attribute in {name}"
        assert "<style" not in html.lower(), f"style element in {name}"


def test_every_page_links_to_privacy_and_terms():
    for name in PAGES:
        p = parse(name)
        assert "/privacy" in p.hrefs and "/terms" in p.hrefs, name


def test_no_third_party_resources():
    for name in PAGES:
        for res in parse(name).resources:
            assert res and res.startswith(("/", "#")) and not res.startswith("//"), f"{name} loads {res}"
    assert "http" not in re.sub(r"url\(\"/static/[^\"]+\"\)", "", read("style.css")).lower()


def test_internal_links_resolve():
    for name in PAGES:
        p = parse(name)
        for href in p.hrefs:
            if href.startswith("https://"):
                assert href.startswith("https://github.com/Danielraj5605/ScamShield"), f"{name}: unexpected external link {href}"
            elif href.startswith("#"):
                assert href[1:] in p.ids, f"{name}: missing anchor {href}"
            elif href.startswith("/static/"):
                assert (WEB / href[len("/static/"):]).is_file(), f"{name}: {href}"
            else:
                assert href in ROUTES, f"{name}: unknown link {href}"


def test_stylesheet_font_files_are_referenced_and_present():
    css = read("style.css")
    for m in re.finditer(r'url\("/static/(fonts/[^"]+)"\)', css):
        assert (WEB / m.group(1)).is_file(), m.group(1)


def test_policies_state_the_facts_the_code_relies_on():
    privacy = read("privacy.html")
    for must in ("does not store the messages", "no cookies", "never opened", "scrubbed copy", "Last updated"):
        assert must in privacy, must
    terms = read("terms.html")
    for must in ("advice", "not legal, financial", "MIT licence", "1930"):
        assert must in terms, must
